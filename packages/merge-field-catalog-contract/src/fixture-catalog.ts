/*
 * A realistic fixture catalog and a fixture template set — the data the mock provider answers with.
 *
 * "Realistic" is the point: the field-input surfaces are laid out against real-length labels, real
 * key shapes, and a real mix of automatic and conditional fields, so the layout is honest before any
 * endpoint exists. Every example rendering is invented sample text (a made-up firm, a made-up
 * client) — nothing here is or resembles a real person's data.
 *
 * IT IS A PROJECTION, NOT AN INVENTION. Every platform key below is a key the merge-field dictionary
 * actually ships, asserted by `test/fixture-projection.test.ts`. A fixture free to describe fields the
 * engine does not have is a second catalogue with its own way of being wrong — and it had already
 * grown a practice area, a court case number, and a responsible attorney that nothing could fill in.
 * The firm-defined `custom.<handle>` entries are the one exception, because a firm's own fields exist
 * per firm and by construction not in the platform's list; their handles carry the real minted shape so
 * the surfaces are laid out against keys of the real length.
 */
