// The two pieces of standing copy the composer shows, held here rather than in a screen so the web
// application and the desktop shell say the same words, and so changing them is one edit reviewed
// once.
//
// The framing is operational and about this board, not abstract and about a duty the reader already
// has. "Do not post about a representation" invites a judgement call and tells a lawyer something
// they know; naming the specific artifacts — a matter number, a balance, a screenshot — is
// actionable at the moment of writing. The authority is cited in one clause at the end for the
// reader who wants it, because the thing practitioners do not always know is not "be careful", it
// is that a hypothetical counts.

// Shown before a member's first post and dismissible permanently thereafter. A modal on every post
// is patronising, goes unread within a week, and buys nothing legally.
export const FIRST_POST_NOTICE =
  "This board is about the software. Do not include client names, matter numbers, ledger balances, party names, or screenshots of your own data — a question that needs those belongs in support, where it stays confidential. (ABA Formal Opinion 511R holds that a post can breach confidentiality even in hypothetical form, where a reader could infer the client or the situation.)";

// Stands permanently beside the composer. Facts about the venue, not advice: what a reader can see,
// what a search engine cannot, and that undoing it is the member's own one-click action rather than
// a request to somebody else.
export const COMPOSER_VENUE_NOTICE =
  "Anyone can read this board without signing in. Search engines are asked not to index it, and you can delete anything you post instantly.";

// The composer offers this alongside the notice, because telling an author their question is in the
// wrong place obliges the same gesture to offer the right one.
export const SEND_TO_SUPPORT_LABEL = "Send this to support instead";

// Why attachments are not offered, shown where a member reaches for one. Stated as the trade it is
// rather than as a limitation, because the demand is legitimate and the answer is a redirection.
export const ATTACHMENTS_UNAVAILABLE_NOTICE =
  "Screenshots and file attachments are not available on this board. A screen capture of your own workspace usually carries a client name, a matter number and a balance, and an image cannot be read for those the way text can. Send it to support instead, where it stays confidential.";
