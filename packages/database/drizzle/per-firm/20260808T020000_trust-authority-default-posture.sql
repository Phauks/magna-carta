-- THE FIRM'S SHIPPED MONEY-OUT POSTURE BECOMES AUTHORITY-BASED, AS DATA. A member holding the
-- authority capability (trust:authorize) releases client money alone; a member without it raises a
-- request that only somebody holding it can settle. That is the stored triple
-- (policy = 'off', threshold = NULL, require_authorized_approver = 1): the authority flag binds
-- whoever LETS MONEY GO — the second-person approver and the sole actor on an exempt amount alike —
-- so an amount no second person is required for can still only be released by a holder, and a
-- non-holder's self-decision is refused, leaving the request pending for one.
--
-- WRITTEN AS A VERSION ROW, NOT AS A RE-READING OF THE ABSENT ROW. The alternative was to change
-- what "no policy row" means, which would have needed three shipped triggers dropped and recreated
-- and would have silently changed the meaning of the NULL stamp on every request submitted before
-- any posture existed — a stamp that is itself the historical record of those requests. Seeding is
-- purely additive: no trigger is touched, the absent-row reading keeps describing exactly the
-- history it describes, and the new posture is auditable data in the firm's own posture history,
-- with a version number and a set_at like every other posture.
--
-- ONLY ON AN EMPTY TABLE. A firm that has already written its own posture keeps it — this seed must
-- never append a version over a decision a firm made, and version 1 over an existing version 1 would
-- abort the whole migration on the dense-version trigger and leave that firm's database unmigrated.
-- The guard is therefore load-bearing twice: it protects the firm's choice and it protects the
-- lineage.
--
-- WHAT THIS CHANGES FOR A FIRM WITH NO ROW: it had always-two-person with no authority requirement,
-- and now has authority-holder-solo. That is a real relaxation, taken deliberately on the owner's
-- direction, and it is why it is recorded as a version a firm can read, supersede, and audit rather
-- than as a platform default nothing names.
--
-- set_by is NOT NULL and no person set this, so it carries a platform sentinel meaning "the posture
-- the platform shipped" — well-formed as a handle so nothing downstream has to special-case its
-- shape, and belonging to no member, so a reader can never mistake it for somebody's decision. The
-- seed writes no audit_log row: the append-only version row IS the record, and a change made BY a
-- member still writes trust.authorization_policy_changed as before.
INSERT INTO `trust_authorization_policy` (`id`, `version`, `policy`, `threshold_amount_minor`, `require_authorized_approver`, `set_by`, `set_at`)
SELECT 'trustAuthorizationPolicy_platformDefault000000', 1, 'off', NULL, 1, 'user_platformPosture000000', '2026-08-08T02:00:00.000Z'
WHERE NOT EXISTS (SELECT 1 FROM `trust_authorization_policy`);
