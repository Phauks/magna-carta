-- The signed agreement behind a fee arrangement version.
--
-- A fee arrangement is what the client agreed to, and until now the record held the terms and not
-- the paper: the intake agreement the client signs when the matter opens, or the amendment they sign
-- later, lived in the matter's files with nothing tying the version to it. This column is that tie —
-- an ordinary matter file, exactly as the conflicts waiver records its evidencing document — so the
-- version can point at the agreement the firm can actually produce.
--
-- Nullable, and deliberately so: every version already on the books predates the column, and a
-- version may honestly be recorded before the paper is filed. Purely additive, so the append-only
-- table is not rebuilt and its triggers are untouched. Column comment lives beside the Drizzle
-- definition in packages/database/src/per-firm-schema.ts.
ALTER TABLE `matter_billing_arrangement` ADD COLUMN `agreement_file_id` text REFERENCES `file`(`id`);--> statement-breakpoint
