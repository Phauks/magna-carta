-- What a sealed identifier is OF, in the clear.
--
-- A list of sealed identifiers used to be a list of types: "Driver's license · sealed", "Account
-- · sealed". A licence number means nothing without the state that issued it, a bar number nothing
-- without its jurisdiction, and an account number with nothing it is held with cannot be used or
-- even recognized — and none of those facts is a secret. This column holds that plaintext part so
-- the list can name what it holds while the value stays sealed. Never the value or any part of it;
-- null for a type with nothing to say beside the seal (a social security number).
--
-- Nullable and additive: every row on the books predates the column, and a type may honestly have
-- no label. Column comment lives beside the Drizzle definition in
-- packages/database/src/per-firm-schema.ts.
ALTER TABLE `directory_identifier` ADD COLUMN `label` text;--> statement-breakpoint
