-- The format a shelf item was MADE for, which is a different fact from the formats it has been
-- taken in.
--
-- Why it is needed now: exporting no longer downloads a file. A member picks a format on the export
-- control and the item is generated onto their shelf, so several can be taken together later. That
-- choice has to survive until they download it — without this column the format they asked for is
-- lost the moment the menu closes, and the shelf would have to guess one or ask again.
--
-- Kept DISTINCT from downloaded_formats_json rather than folded into it. "What this was made for"
-- and "what has actually left the platform" answer different questions: the first defaults the
-- download button, the second is the record of what the member already has, and a member who takes
-- a Word copy of a report generated as Excel has both facts true at once.
--
-- Nullable, because every row written before this column existed was generated by the old
-- download-and-keep path, where the format asked for WAS the format taken — those rows answer the
-- question from downloaded_formats_json and inventing a value for them would state something nobody
-- recorded. Additive: no rewrite, no default backfill.
ALTER TABLE `download_item` ADD COLUMN `requested_format` text;
