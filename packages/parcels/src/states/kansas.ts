import type { AssessorSite } from "../types.ts";
import { stateSites } from "./helpers.ts";

// Kansas's 105 counties. The statewide DASC/ORKA parcel portal backs ~50 mostly-rural counties
// (search-only, county selected by `countyName=`); the rest are CIC Hosting, kansasgov/Aumentum, Beacon,
// Tyler, or self-run metro systems (Johnson, Sedgwick, Shawnee, Wyandotte). Public-APN deep-links: the
// six Beacon counties (Cowley, Dickinson, Lyon, Miami, Montgomery, Reno) and the two CIC counties
// Wilson + Woodson (`Details.aspx?pid={apn}`). Riley is Beacon but its AppID was unconfirmed, so it
// stays search-only. (Cloud County 20031 was missing from the research batch — added here via ORKA.)
const { search, template, platform } = stateSites("KS");

const orka = (jurisdictionId: string, name: string): AssessorSite =>
  search(jurisdictionId, name, `https://www.kansasgis.org/orka/intro.cfm?countyName=${name}`);

const beacon = (jurisdictionId: string, name: string, appId: string, layerId: string): AssessorSite =>
  platform(
    jurisdictionId,
    name,
    `https://beacon.schneidercorp.com/Application.aspx?AppID=${appId}&LayerID=${layerId}&PageTypeID=2`,
    "beaconQpublic",
    "beacon.schneidercorp.com",
    { params: { appId, layerId } },
  );

const cic = (jurisdictionId: string, name: string, host: string): AssessorSite =>
  template(
    jurisdictionId,
    name,
    `https://${host}/webportal/appraiser`,
    `https://${host}/webportal/appraiser/Details.aspx?pid={apn}`,
  );

