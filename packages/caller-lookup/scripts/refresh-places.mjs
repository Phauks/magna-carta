/*
 * Rebuilds the two free place tables from libphonenumber's data files.
 *
 * Usage: node packages/caller-lookup/scripts/refresh-places.mjs <geocoding/en/1.txt> <timezones/map_data.txt>
 *
 * Both inputs are in https://github.com/google/libphonenumber under `resources/`. The script writes
 * src/north-american-exchanges.ts and src/north-american-time-zones.ts; the area-code table beside
 * them is kept by hand because it carries two corrected labels.
 *
 * WHY A SCRIPT. The exchange table is some thirty thousand rows. Nobody reviews that by eye, so what
 * is reviewed is this transformation, and a refresh is one command rather than an edit.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const [geocodingFile, timeZoneFile] = process.argv.slice(2);
if (geocodingFile === undefined || timeZoneFile === undefined) {
  console.error("Usage: refresh-places.mjs <geocoding/en/1.txt> <timezones/map_data.txt>");
  process.exit(1);
}

const SOURCE_DIRECTORY = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "src");

function rows(file) {
  return readFileSync(file, "utf8")
    .split("\n")
    .filter((line) => line.startsWith("1") && line.includes("|"))
    .map((line) => {
      const [prefix, value] = line.split("|");
      return { digits: prefix.slice(1), value: value.trim() };
    });
}

const LICENCE =
  "// Derived from libphonenumber (https://github.com/google/libphonenumber), Copyright (C) 2011 The\n" +
  "// Libphonenumber Authors, licensed under the Apache License, Version 2.0\n" +
  "// (http://www.apache.org/licenses/LICENSE-2.0). Generated by scripts/refresh-places.mjs; do not\n" +
  "// edit by hand.\n";

// Exchanges: the rows longer than an area code, grouped by area code, each place named once.
const places = [];
const placeIndex = new Map();
const byAreaCode = new Map();
for (const { digits, value } of rows(geocodingFile)) {
  if (digits.length <= 3 || !/^[2-9][0-9]{3,5}$/.test(digits)) continue;
  if (!placeIndex.has(value)) {
    placeIndex.set(value, places.length);
    places.push(value);
  }
  const areaCode = digits.slice(0, 3);
  const entries = byAreaCode.get(areaCode) ?? [];
  entries.push(`${digits.slice(3)}:${placeIndex.get(value).toString(36)}`);
  byAreaCode.set(areaCode, entries);
}

writeFileSync(
  path.join(SOURCE_DIRECTORY, "north-american-exchanges.ts"),
  `${LICENCE}//
// Which place an exchange (the three digits after the area code) was assigned to, for the area codes
// the source subdivides. Each area code's entry is a space-separated list of \`digits:place\`, where
// the digits continue the number after the area code (one to three of them; the longest match wins)
// and the place is a base-36 index into EXCHANGE_PLACES. Packed this way because the table has
// ${byAreaCode.size} area codes and ${[...byAreaCode.values()].reduce((sum, entries) => sum + entries.length, 0)} rows, and is read only for the one area code being asked about.
export const EXCHANGE_PLACES: readonly string[] = ${JSON.stringify(places)};

export const EXCHANGES_BY_AREA_CODE: Readonly<Record<string, string>> = {
${[...byAreaCode.entries()]
  .toSorted(([left], [right]) => left.localeCompare(right))
  .map(([areaCode, entries]) => `  "${areaCode}": "${entries.join(" ")}",`)
  .join("\n")}
};
`,
);

// Time zones: one IANA zone per prefix. A prefix the source says spans several zones is KEPT, with
// an empty zone, so a longer prefix inside a single-zone area code still overrides it and a shorter
// single-zone prefix never answers for it: the lookup says "not known" rather than picking one.
const zones = rows(timeZoneFile)
  .filter(({ digits }) => digits.length >= 3)
  .map(({ digits, value }) => ({ digits, value: value.includes("&") ? "" : value }));
writeFileSync(
  path.join(SOURCE_DIRECTORY, "north-american-time-zones.ts"),
  `${LICENCE}//
// The IANA time zone a North American number's prefix (the digits after the 1: an area code, or an
// area code and part of an exchange where a code spans two zones) was assigned to. The longest
// matching prefix wins. A prefix the source places in more than one zone carries an empty zone, and
// so answers "not known" rather than a guess.
export const NORTH_AMERICAN_TIME_ZONES: ReadonlyMap<string, string> = new Map([
${zones.map(({ digits, value }) => `  ["${digits}", "${value}"],`).join("\n")}
]);
`,
);

console.log(
  `refresh-places: ${places.length} places over ${byAreaCode.size} area codes; ${zones.length} time zone prefixes`,
);
