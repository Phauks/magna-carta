import type { AssessorSite } from "../types.ts";
import { stateSites } from "./helpers.ts";

// Nebraska's 93 counties. Two shared portals dominate, both search-only: Nebraska Taxes Online
// (MIPS, `search.aspx?county={code}`) and gWorks GIS (`{county}.gworks.com`). Only Gosper exposes a
// clean public-APN deep-link (qPublic/Beacon with AppID/LayerID); Colfax and Douglas (Omaha) run
// Beacon search pages but without a KeyValue deep-link, so they stay search-only.
const { search, platform } = stateSites("NE");

const nto = (jurisdictionId: string, name: string, code: string): AssessorSite =>
  search(jurisdictionId, name, `https://www.nebraskataxesonline.us/search.aspx?county=${code}`);

const gworks = (jurisdictionId: string, name: string, slug: string): AssessorSite =>
  search(jurisdictionId, name, `https://${slug}.gworks.com/`);

