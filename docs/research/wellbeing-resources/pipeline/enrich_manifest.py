#!/usr/bin/env python3
"""Regenerate sources/manifest.yaml and sources/_collection-worklist.tsv from the capture files.

Each capture file (sources/US-XX/*.txt) starts with a `---` front-matter block:
    ---
    jurisdiction: US-XX
    publisher: ...
    sourceUrl: ...
    accessedOn: YYYY-MM-DD
    accessGate: open|paywall|form
    method: ...
    ---
This script parses those headers, computes the sha256 of each file, and rewrites the manifest +
worklist so provenance stays regenerable (never hand-edit them). Run from
docs/research/wellbeing-resources/.
"""
import hashlib
from pathlib import Path

ROOT = Path(__file__).parent.parent
SRC = ROOT / "sources"
FIELDS = ("jurisdiction", "publisher", "sourceUrl", "accessedOn", "accessGate", "method")


def parse_header(text):
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return None
    hdr = {}
    for line in lines[1:]:
        if line.strip() == "---":
            break
        if ":" in line:
            k, _, v = line.partition(":")
            hdr[k.strip()] = v.strip()
    return hdr


def main():
    entries = []
    for f in sorted(SRC.rglob("*.txt")):
        raw = f.read_bytes()
        hdr = parse_header(raw.decode("utf-8", "replace"))
        if hdr is None:
            print(f"WARNING: {f.relative_to(ROOT)} has no front-matter header; skipped")
            continue
        sha = hashlib.sha256(raw).hexdigest()
        rel = f.relative_to(SRC).as_posix()
        entries.append({**{k: hdr.get(k, "") for k in FIELDS}, "path": rel, "sha256": sha})

    entries.sort(key=lambda e: (e["jurisdiction"], e["path"]))

    # manifest.yaml
    out = ["# Provenance for every captured source. GENERATED by pipeline/enrich_manifest.py.",
           "# sha256 is of the captured .txt file (front-matter + body). Do not hand-edit.",
           "schemaVersion: 1", "sources:"]
    for e in entries:
        out.append(f"  - jurisdiction: {e['jurisdiction']}")
        out.append(f"    path: {e['path']}")
        out.append(f"    publisher: {e['publisher']!r}")
        out.append(f"    sourceUrl: {e['sourceUrl']}")
        out.append(f"    accessedOn: {e['accessedOn']}")
        out.append(f"    accessGate: {e['accessGate']}")
        out.append(f"    sha256: {e['sha256']}")
    (SRC / "manifest.yaml").write_text("\n".join(out) + "\n", encoding="utf-8")

    # _collection-worklist.tsv
    rows = ["sourceKey\tjurisdiction\tsourceUrl\tmethod\taccessedOn\tnotes"]
    for e in entries:
        key = e["path"].split("/")[-1].removesuffix(".txt")
        rows.append(f"{key}\t{e['jurisdiction']}\t{e['sourceUrl']}\t{e['method']}\t{e['accessedOn']}\t")
    (SRC / "_collection-worklist.tsv").write_text("\n".join(rows) + "\n", encoding="utf-8")

    print(f"enriched: {len(entries)} sources -> manifest.yaml + _collection-worklist.tsv")


if __name__ == "__main__":
    main()
